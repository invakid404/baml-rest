// TestStreamPostClaimFaultMatrix injects each post-claim transport/protocol/parse fault
// and asserts ONE terminal result with exactly one provider request and no resend.
func TestStreamPostClaimFaultMatrix(t *testing.T) {
	tr := loadTranscript(t)
	emitted := nativespinejsonfixture.StreamBinding()

	partialDecodeErr := emitted
	partialDecodeErr.DecodePartial = func([]byte) (any, error) { return nil, errors.New("forced partial decode error") }
	// The P1 regression: a DECODER error whose chain contains the PARSER's "no partial
	// for this prefix yet" sentinel. Only the parser's own no-partial outcome is benign,
	// and it is resolved before the decoder runs — so this must still be TERMINAL. A
	// cadence (or a parse closure) that applied errors.Is(ErrDeBAMLParseUnsupported) to
	// the combined parser+decoder error would swallow it into a no-event and the stream
	// would wrongly SUCCEED.
	partialDecodeSentinel := emitted
	partialDecodeSentinel.DecodePartial = func([]byte) (any, error) {
		return nil, fmt.Errorf("decode static alias stream: %w", bamlutils.ErrDeBAMLParseUnsupported)
	}
	partialDecodePanic := emitted
	partialDecodePanic.DecodePartial = func([]byte) (any, error) { panic("forced partial decode panic") }
	finalDecodeErr := emitted
	finalDecodeErr.Unary.DecodeFinal = func([]byte) (any, error) { return nil, errors.New("forced final decode error") }

	type row struct {
		name       string
		binding    bamlutils.NativeSpineStreamBinding
		handler    func(w http.ResponseWriter, r *http.Request)
		wantStage  string
		wantReason string
	}
	rows := []row{
		{
			name:    "provider_non_2xx_preserved",
			binding: emitted,
			handler: func(w http.ResponseWriter, r *http.Request) {
				w.Header().Set("Content-Type", "application/json")
				w.WriteHeader(http.StatusTooManyRequests)
				_, _ = w.Write([]byte(`{"error":"slow down"}`))
			},
			wantStage: "provider", wantReason: "provider_error",
		},
		{
			name:    "invalid_content_type",
			binding: emitted,
			handler: func(w http.ResponseWriter, r *http.Request) {
				w.Header().Set("Content-Type", "application/json")
				w.WriteHeader(http.StatusOK)
				_, _ = w.Write([]byte(`{"not":"a stream"}`))
			},
			wantStage: "transport", wantReason: "stream_protocol_error",
		},
		{
			name:      "partial_decoder_failure_is_terminal",
			binding:   partialDecodeErr,
			handler:   func(w http.ResponseWriter, r *http.Request) { writeSSE(w, transcriptBody(tr), 0) },
			wantStage: "stream", wantReason: "emit_error",
		},
		{
			name:      "partial_decoder_error_wrapping_the_parser_sentinel_is_terminal",
			binding:   partialDecodeSentinel,
			handler:   func(w http.ResponseWriter, r *http.Request) { writeSSE(w, transcriptBody(tr), 0) },
			wantStage: "stream", wantReason: "emit_error",
		},
		{
			name:      "partial_decoder_panic_is_terminal",
			binding:   partialDecodePanic,
			handler:   func(w http.ResponseWriter, r *http.Request) { writeSSE(w, transcriptBody(tr), 0) },
			wantStage: "stream", wantReason: "panic",
		},
		{
			name:      "final_decoder_failure_is_terminal",
			binding:   finalDecodeErr,
			handler:   func(w http.ResponseWriter, r *http.Request) { writeSSE(w, transcriptBody(tr), 0) },
			wantStage: "decode", wantReason: "carrier_decode_error",
		},
	}

	for _, tc := range rows {
		t.Run(tc.name, func(t *testing.T) {
			lb := newLoopback(t, tc.handler)
			e := newJSONStreamExec(t, lb.baseURL(), nil, tc.binding)
			c := &collector{}
			res := e.Stream(streamAdapterFor(bamlutils.StreamModeStreamWithRaw, false), jsonAliasMethod, jsonInput(), c.emit)

			assertTerminal(t, res, lb, 1)
			if res.Stage != tc.wantStage || res.Reason != tc.wantReason {
				t.Fatalf("(stage, reason) = (%q, %q), want (%q, %q)", res.Stage, res.Reason, tc.wantStage, tc.wantReason)
			}
			if snap := e.Metrics().Snapshot(); snap.Claims != 1 || snap.Failures != 1 || snap.Successes != 0 {
				t.Fatalf("metrics = %+v, want exactly one claim and one failure", snap)
			}
		})
	}
}

