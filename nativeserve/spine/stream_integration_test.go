// TestStreamServesTheSharedTranscript is the acceptance row for both real stream modes:
// the public event sequence equals the SHARED expected transcript exactly — emit/no-emit
// decisions, partial bytes, order, and the final — with exactly one provider request.
func TestStreamServesTheSharedTranscript(t *testing.T) {
	tr := loadTranscript(t)

	for _, tc := range []struct {
		name     string
		mode     bamlutils.StreamMode
		needsRaw bool
	}{
		{"stream", bamlutils.StreamModeStream, false},
		{"stream_with_raw", bamlutils.StreamModeStreamWithRaw, true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			lb := newLoopback(t, func(w http.ResponseWriter, r *http.Request) {
				writeSSE(w, transcriptBody(tr), 0)
			})
			e := newJSONStreamExec(t, lb.baseURL(), nil)
			c := &collector{}
			res := e.Stream(streamAdapterFor(tc.mode, false), jsonAliasMethod, jsonInput(), c.emit)

			if res.Disposition != bamlutils.NativeSpineStreamSucceeded {
				t.Fatalf("disposition = %v (stage %q reason %q err %v), want succeeded", res.Disposition, res.Stage, res.Reason, res.Err)
			}
			if lb.count() != 1 {
				t.Fatalf("provider request count = %d, want exactly 1", lb.count())
			}

			// The FINAL is the value carrier and marshals to the expected bytes.
			finalBytes, err := json.Marshal(res.Final)
			if err != nil {
				t.Fatalf("marshal final: %v", err)
			}
			if string(finalBytes) != tr.Final {
				t.Fatalf("final = %s, want %s", finalBytes, tr.Final)
			}
			if _, ok := res.Final.(nativespinejsonfixture.OutputJson); !ok {
				t.Fatalf("final has Go type %T, want the FINAL value carrier OutputJson", res.Final)
			}

			// The STRUCTURED events, in order, are exactly the transcript's emitting
			// deltas. Raw-only frames appear on /stream-with-raw only and are checked
			// separately below, so filter them here.
			var structured []collectedEvent
			var rawOnly int
			for _, ev := range c.snapshot() {
				if ev.hasPartial {
					structured = append(structured, ev)
					continue
				}
				rawOnly++
			}
			var want []string
			for _, d := range tr.Deltas {
				if d.Emit {
					want = append(want, d.Partial)
				}
			}
			if len(structured) != len(want) {
				t.Fatalf("got %d structured partial(s), want %d", len(structured), len(want))
			}
			for i := range want {
				if structured[i].partial != want[i] {
					t.Fatalf("structured partial %d = %s, want %s", i, structured[i].partial, want[i])
				}
			}

			if tc.needsRaw {
				// /stream-with-raw: raw rides every event and the final carries the
				// accumulated text; the no-emit delta surfaces as a raw-only frame.
				if rawOnly == 0 {
					t.Fatal("/stream-with-raw produced no raw-only frame for the no-partial delta")
				}
				var raw strings.Builder
				for _, ev := range c.snapshot() {
					raw.WriteString(ev.raw)
				}
				if raw.String() != tr.Accumulated {
					t.Fatalf("accumulated per-delta raw = %q, want %q", raw.String(), tr.Accumulated)
				}
				if res.Raw != tr.Accumulated {
					t.Fatalf("final raw = %q, want %q", res.Raw, tr.Accumulated)
				}
			} else {
				// A plain /stream carries NO raw or reasoning anywhere.
				for i, ev := range c.snapshot() {
					if ev.raw != "" || ev.reasoning != "" {
						t.Fatalf("event %d on /stream carries raw=%q reasoning=%q; both must stay empty", i, ev.raw, ev.reasoning)
					}
				}
				if rawOnly != 0 {
					t.Fatalf("/stream produced %d raw-only frame(s), want 0 (the no-partial delta yields no event)", rawOnly)
				}
				if res.Raw != "" || res.Reasoning != "" {
					t.Fatalf("final raw/reasoning = (%q, %q) on /stream; both must stay empty", res.Raw, res.Reasoning)
				}
			}

			if snap := e.Metrics().Snapshot(); snap.Claims != 1 || snap.Sockets != 1 || snap.Successes != 1 || snap.Failures != 0 || snap.Declines != 0 {
				t.Fatalf("metrics = %+v, want exactly one claim/socket/success", snap)
			}
		})
	}
}

// TestStreamWithRawCarriesReasoningInOrder proves reasoning-only chunks reach the public
// transcript in their original order on /stream-with-raw when the adapter opted in, and
// are suppressed when it did not.
func TestStreamWithRawCarriesReasoningInOrder(t *testing.T) {
	body := sseRoleOnly +
		sseReasoningChunk("thinking a") +
		sseChunk(`{"k":1`) +
		sseReasoningChunk("thinking b") +
		sseChunk(`}`) +
		sseDone

	for _, tc := range []struct {
		name          string
		includeReason bool
		wantReasoning string
	}{
		{"include_reasoning", true, "thinking athinking b"},
		{"reasoning_off", false, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			lb := newLoopback(t, func(w http.ResponseWriter, r *http.Request) { writeSSE(w, body, 0) })
			e := newJSONStreamExec(t, lb.baseURL(), nil)
			c := &collector{}
			res := e.Stream(streamAdapterFor(bamlutils.StreamModeStreamWithRaw, tc.includeReason), jsonAliasMethod, jsonInput(), c.emit)
			if res.Disposition != bamlutils.NativeSpineStreamSucceeded {
				t.Fatalf("disposition = %v (err %v), want succeeded", res.Disposition, res.Err)
			}
			var reasoning strings.Builder
			for _, ev := range c.snapshot() {
				reasoning.WriteString(ev.reasoning)
			}
			if reasoning.String() != tc.wantReasoning {
				t.Fatalf("per-event reasoning = %q, want %q", reasoning.String(), tc.wantReasoning)
			}
			if res.Reasoning != tc.wantReasoning {
				t.Fatalf("final reasoning = %q, want %q", res.Reasoning, tc.wantReasoning)
			}
			if lb.count() != 1 {
				t.Fatalf("provider request count = %d, want exactly 1", lb.count())
			}
		})
	}
}

