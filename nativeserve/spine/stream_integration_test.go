// stream_integration_test.go is the M3e-A SSE fragmentation + post-claim fault matrix at
// the spine executor level, driven by a deterministic loopback provider.
//
// Every CLAIMED row proves the same three things: exactly ONE terminal outcome, exactly
// ONE provider request (no resend, no retry, no fallback, no second RoundTrip), and a
// FailedAfterClaim disposition that is never a decline. Every PRE-CLAIM row proves zero
// sockets and zero emitted events; those live in the pure-Go stream_registry_test.go.

// --- transcript fixture -----------------------------------------------------------

type transcriptDelta struct {
	Content string `json:"content"`
	Emit    bool   `json:"emit"`
	Partial string `json:"partial,omitempty"`
}

type transcriptFixture struct {
	Deltas      []transcriptDelta `json:"deltas"`
	Final       string            `json:"final"`
	Accumulated string            `json:"accumulated"`
}

// StructuredCount is how many deltas produce a structured partial event.
func (tr transcriptFixture) StructuredCount() int {
	n := 0
	for _, d := range tr.Deltas {
		if d.Emit {
			n++
		}
	}
	return n
}

// loadTranscript reads the SHARED expected transcript fixture. It is owned and
// regenerated by internal/nativespinejsonfixture (which computes it from the root-owned
// native static-stream parsers plus the emitted decoders), so this module asserts
// against the same table the booted native-only e2e does — and computes no expectation
// at runtime, and imports no BAML to do it.
func loadTranscript(t *testing.T) transcriptFixture {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	// .../nativeserve/spine/stream_integration_test.go -> repo root
	repoRoot := filepath.Clean(filepath.Join(filepath.Dir(file), "..", ".."))
	path := filepath.Join(repoRoot, "internal", "nativespinejsonfixture", "testdata", "stream_transcript.json")
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read shared stream transcript: %v", err)
	}
	var tr transcriptFixture
	if err := json.Unmarshal(raw, &tr); err != nil {
		t.Fatalf("decode shared stream transcript: %v", err)
	}
	if len(tr.Deltas) == 0 || tr.Final == "" {
		t.Fatal("shared stream transcript is empty")
	}
	return tr
}

// --- SSE loopback -----------------------------------------------------------------

// sseChunk renders one OpenAI streaming chunk carrying an assistant content delta.
func sseChunk(content string) string {
	b, _ := json.Marshal(map[string]any{
		"choices": []any{map[string]any{"delta": map[string]any{"content": content}}},
	})
	return "data: " + string(b) + "\n\n"
}

// sseReasoningChunk renders a chunk carrying ONLY provider reasoning text.
func sseReasoningChunk(text string) string {
	b, _ := json.Marshal(map[string]any{
		"choices": []any{map[string]any{"delta": map[string]any{"reasoning_content": text}}},
	})
	return "data: " + string(b) + "\n\n"
}

// The noise frames every real provider interleaves: a role-only opening delta, an empty
// content delta, a finish-only delta, and a usage-only frame. None may produce an event.
const (
	sseRoleOnly   = `data: {"choices":[{"delta":{"role":"assistant"}}]}` + "\n\n"
	sseEmptyDelta = `data: {"choices":[{"delta":{"content":""}}]}` + "\n\n"
	sseFinishOnly = `data: {"choices":[{"delta":{},"finish_reason":"stop"}]}` + "\n\n"
	sseUsageOnly  = `data: {"choices":[],"usage":{"prompt_tokens":1,"completion_tokens":2}}` + "\n\n"
	sseDone       = "data: [DONE]\n\n"
)

// writeSSE writes body to w as an event-stream, flushing after each fragment. fragment
// <= 0 writes the whole body at once; otherwise the body is split into fragment-byte
// pieces, which deliberately splits multi-byte UTF-8 runes across writes.
func writeSSE(w http.ResponseWriter, body string, fragment int) {
	w.Header().Set("Content-Type", "text/event-stream")
	w.WriteHeader(http.StatusOK)
	flusher, _ := w.(http.Flusher)
	b := []byte(body)
	step := len(b)
	if fragment > 0 {
		step = fragment
	}
	for i := 0; i < len(b); i += step {
		end := i + step
		if end > len(b) {
			end = len(b)
		}
		_, _ = w.Write(b[i:end])
		if flusher != nil {
			flusher.Flush()
		}
	}
}

// transcriptBody renders the shared transcript's content deltas, interleaved with the
// noise frames a real provider sends, and terminated with [DONE].
func transcriptBody(tr transcriptFixture) string {
	var b strings.Builder
	b.WriteString(sseRoleOnly)
	for _, d := range tr.Deltas {
		b.WriteString(sseChunk(d.Content))
		b.WriteString(sseEmptyDelta)
	}
	b.WriteString(sseFinishOnly)
	b.WriteString(sseUsageOnly)
	b.WriteString(sseDone)
	return b.String()
}

// --- executor + drive helpers ------------------------------------------------------

// collectedEvent is one public event the executor delivered.
type collectedEvent struct {
	hasPartial bool
	partial    string
	raw        string
	reasoning  string
}

// collector records events and can inject an emit failure or panic at a chosen index.
type collector struct {
	mu       sync.Mutex
	events   []collectedEvent
	failAt   int // 1-based; 0 disables
	panicAt  int // 1-based; 0 disables
	failWith error
}

func (c *collector) emit(ev bamlutils.NativeSpineStreamEvent) error {
	c.mu.Lock()
	defer c.mu.Unlock()
	n := len(c.events) + 1
	if c.panicAt == n {
		panic("forced emit panic")
	}
	if c.failAt == n {
		return c.failWith
	}
	e := collectedEvent{hasPartial: ev.HasPartial, raw: ev.Raw, reasoning: ev.Reasoning}
	if ev.HasPartial {
		b, err := json.Marshal(ev.Partial)
		if err != nil {
			return fmt.Errorf("marshal partial: %w", err)
		}
		e.partial = string(b)
	}
	c.events = append(c.events, e)
	return nil
}

func (c *collector) snapshot() []collectedEvent {
	c.mu.Lock()
	defer c.mu.Unlock()
	out := make([]collectedEvent, len(c.events))
	copy(out, c.events)
	return out
}

func streamAdapterFor(mode bamlutils.StreamMode, reasoning bool) *testAdapter {
	a := newTestAdapter()
	a.SetStreamMode(mode)
	a.SetIncludeReasoning(reasoning)
	return a
}

func jsonInput() *nativespinejsonfixture.StaticRecursiveAliasJsonInput {
	return &nativespinejsonfixture.StaticRecursiveAliasJsonInput{Topic: "weather"}
}

// assertTerminal asserts a claimed row's shape: FailedAfterClaim, a typed error, and
// exactly one provider request.
func assertTerminal(t *testing.T, res bamlutils.NativeSpineStreamResult, lb *loopback, wantHits int64) {
	t.Helper()
	if res.Disposition != bamlutils.NativeSpineStreamFailedAfterClaim {
		t.Fatalf("disposition = %v (stage %q reason %q err %v), want failed_after_claim", res.Disposition, res.Stage, res.Reason, res.Err)
	}
	if res.Err == nil {
		t.Fatal("a failed-after-claim result carries no typed error")
	}
	if res.Final != nil {
		t.Fatal("a failed-after-claim result carries a final value")
	}
	if got := lb.count(); got != wantHits {
		t.Fatalf("provider request count = %d, want exactly %d (no resend, no retry, no fallback)", got, wantHits)
	}
}

